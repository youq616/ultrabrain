/** Real Git + PostgreSQL + MCP dispatcher evidence binding, in isolated test storage. */
import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync,spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {connect,loadNative} from '../src/runtime.mjs';
import {runObserved} from '../src/verify-run.mjs';
import {recordExecution} from '../src/projects.mjs';
assert.equal(process.env.ULTRABRAIN_TEST_ALLOW_WRITE,'1');
const cwd=mkdtempSync(join(tmpdir(),'ub-real-git-'));
const git=(...args)=>execFileSync('git',args,{cwd,encoding:'utf8',stdio:['ignore','pipe','pipe']}).trim();
git('init','-q');git('config','user.name','Fixture');git('config','user.email','fixture@example.invalid');
writeFileSync(join(cwd,'code.txt'),'first');git('add','.');git('commit','-qm','fixture');
const revision=git('rev-parse','HEAD');
const engine=await connect({migrate:true});
const {dispatchToolCall}=await loadNative('src/mcp/dispatch.ts');
const source=`evidence-${Date.now().toString(36)}`,project='git-bound';
const auth={token:'test-only',clientId:'evidence-ci',principal:{kind:'oauth_client',id:'evidence-ci'},sourceId:source,scopes:['read','write']};
const call=async(name,args,extra={})=>{
  const r=await dispatchToolCall(engine,name,args,{sourceId:source,remote:true,transport:'stdio',auth,...extra});
  const data=JSON.parse(r.content[0].text);if(r.isError)throw Object.assign(new Error(data.error),{code:data.error});return data;
};
let checks=0;const check=()=>checks++;
const task={id:'tests',title:'Verify selected commit',acceptance:['Pass'],status:'in_progress',code_revision:revision};
const state={goal:'Test version-specific completion',tasks:[task]};
const save=(s,event,rev=1)=>call('ultra_project_save',{project_id:project,expected_revision:rev,event_id:event,state:s});
const completed=id=>({...state,tasks:[{...task,status:'verified_complete',receipt_ids:[id]}]});
try {
  await engine.executeRaw('INSERT INTO sources(id,name) VALUES($1,$1)',[source]);
  await save(state,'create',0);
  const r=await recordExecution(engine,source,project,task,await runObserved([process.execPath,'-e','0'],{cwd}));
  assert.equal(r.code_revision_matched,true);check();
  const evidence=await call('ultra_project_evidence',{project_id:project,receipt_id:r.receipt_id});
  assert.equal(evidence.workspace.before.commit,revision);assert.equal(typeof evidence.workspace,'object');check();
  assert.equal((await call('ultra_project_evidence',{project_id:project,receipt_id:r.receipt_id},{auth:{...auth,scopes:['read']}})).receipt_id,r.receipt_id);check();
  for(const p of [{project_id:'other',receipt_id:r.receipt_id}])await assert.rejects(call('ultra_project_evidence',p),{code:'not_found'});check();
  await assert.rejects(call('ultra_project_evidence',{project_id:project,receipt_id:r.receipt_id},{sourceId:'default',auth:{...auth,sourceId:'default'}}),{code:'not_found'});check();
  await assert.rejects(call('ultra_project_evidence',{project_id:project,receipt_id:r.receipt_id},{auth:{...auth,boundSlugPrefixes:['limited/']}}));check();
  const {workspace,...legacy}=await runObserved([process.execPath,'-e','0'],{cwd});
  const old=await recordExecution(engine,source,project,task,legacy);
  await assert.rejects(save(completed(old.receipt_id),'legacy'),{code:'evidence_required'});check();
  writeFileSync(join(cwd,'code.txt'),'dirty');
  const dirty=await recordExecution(engine,source,project,task,await runObserved([process.execPath,'-e','0'],{cwd}));
  assert.equal(dirty.code_revision_matched,false);
  await assert.rejects(save(completed(dirty.receipt_id),'dirty'),{code:'evidence_required'});check();
  git('checkout','--','code.txt');git('commit','--allow-empty','-qm','second');
  const other=await recordExecution(engine,source,project,task,await runObserved([process.execPath,'-e','0'],{cwd}));
  await assert.rejects(save(completed(other.receipt_id),'wrong-head'),{code:'evidence_required'});check();
  const changed={...state,tasks:[{...task,code_revision:git('rev-parse','HEAD'),status:'verified_complete',receipt_ids:[r.receipt_id]}]};
  await assert.rejects(save(changed,'old-tests-new-target'),{code:'evidence_required'});check();
  const cli=fileURLToPath(new URL('../src/cli.mjs',import.meta.url));
  const cliArgs=[cli,'verify','--source',source,'--project',project,'--task',task.id,'--',process.execPath,'-e','0'];
  const mismatch=spawnSync(process.execPath,cliArgs,{cwd,env:process.env,encoding:'utf8',timeout:15000});
  assert.equal(mismatch.status,2,mismatch.stderr);assert.equal(JSON.parse(mismatch.stdout).code_revision_matched,false);check();
  git('checkout','-q',revision);
  const matched=spawnSync(process.execPath,cliArgs,{cwd,env:process.env,encoding:'utf8',timeout:15000});
  assert.equal(matched.status,0,matched.stderr);assert.equal(JSON.parse(matched.stdout).code_revision_matched,true);check();
  assert.equal((await save(completed(r.receipt_id),'valid')).revision,2);check();
  const {operations}=await loadNative('src/core/operations.ts');
  assert.ok(!operations.some(o=>['ultra_execute','ultra_verify_run','ultra_record_execution'].includes(o.name)));check();
  console.log(`PASS ${checks} real revision-evidence checks (Git, JSONB, scoped MCP, stale/dirty/legacy rejection)`);
} finally {await engine.disconnect();rmSync(cwd,{recursive:true,force:true});}
